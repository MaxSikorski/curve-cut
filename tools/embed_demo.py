#!/usr/bin/env python3
"""Embed the demo model for file:// use.

Browsers refuse fetch()/XHR of local files on file:// pages, so the demo STL is
shipped the same way the Manifold WASM is: compressed + base64 in a classic
script that sets a window global. Re-run after swapping the demo model.

    uv run --no-project python tools/embed_demo.py

Reads  assets/demo/Voron_Design_Cube_v8.STL
Writes assets/demo/voron-cube.stl.b64.js  (window.DEMO_MODEL_B64, zlib+base64)

Exit 0 on success, 1 on failure.
"""

import base64
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "demo" / "Voron_Design_Cube_v8.STL"
DST = ROOT / "assets" / "demo" / "voron-cube.stl.b64.js"

HEADER = """\
// Voron Design Cube v8 — demo model for the first-visit tour.
// Copyright Voron Design (https://vorondesign.com), GPL-3.0 — see LICENSE here.
// Generated by tools/embed_demo.py from Voron_Design_Cube_v8.STL — do not edit.
// zlib-compressed binary STL, base64; decode with fflate.unzlibSync at runtime.
"""


def main() -> int:
    if not SRC.exists():
        print(f"FAIL: missing {SRC}")
        return 1
    raw = SRC.read_bytes()
    packed = zlib.compress(raw, 9)
    b64 = base64.b64encode(packed).decode("ascii")
    DST.write_text(f'{HEADER}window.DEMO_MODEL_B64 = "{b64}";\n')
    print(
        f"ok   {DST.relative_to(ROOT)}: {len(raw):,} B stl -> "
        f"{len(packed):,} B zlib -> {len(b64):,} B base64"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
