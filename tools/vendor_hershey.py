#!/usr/bin/env python3
"""vendor_hershey.py — vendor the Hershey "futural" single-stroke font as a classic script.

Big Print engraves part IDs (A1, B2-L3, ...) into cut faces. A single-stroke vector
font is ideal: each glyph is a set of polylines we can offset into fat outlines with
Manifold's CrossSection and extrude/subtract. The Hershey fonts (Dr. A.V. Hershey,
US NBS, 1967) are public domain; "futural" is the sans-serif simplex variant.

Downloads futural.jhf (kamalmostafa/hershey-fonts mirror of the canonical
distribution), parses the JHF format, and emits vendor/hershey/hershey-font.js
defining window.HERSHEY_FONT — all 95 printable-ASCII glyphs (~15 KB). The emitted
file is committed, so the artifact is reproducible via git even if the URL moves.

JHF format, per line (long glyphs wrap — continuation lines are appended first):
  cols 0-4 glyph id · cols 5-7 vertex count N (includes the L/R pair) ·
  then N char-pairs: first pair = left/right extents, rest = vertices,
  coordinate = ord(char) - ord('R'), the pair " R" = pen up (stroke break).
Y grows DOWNWARD in Hershey data; consumers flip as needed.

Run:  uv run --no-project python tools/vendor_hershey.py
Exit 0 on success, 1 on any failure. Safe to re-run (overwrites).
"""

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "vendor" / "hershey" / "hershey-font.js"
URL = "https://raw.githubusercontent.com/kamalmostafa/hershey-fonts/master/hershey-fonts/futural.jhf"


def unwrap_lines(raw: str) -> list[str]:
    """Rejoin wrapped glyph records: a record starts with a digit in col 0-4."""
    records: list[str] = []
    for line in raw.splitlines():
        if not line.strip():
            continue
        if line[:5].strip().isdigit() and len(line) >= 8:
            records.append(line)
        elif records:
            records[-1] += line
    return records


def parse_glyph(rec: str):
    nverts = int(rec[5:8])
    body = rec[8:]
    pairs = [body[i : i + 2] for i in range(0, 2 * nverts, 2)]
    if len(pairs) != nverts or any(len(p) != 2 for p in pairs):
        raise ValueError(f"short record: {rec[:20]}...")
    left = ord(pairs[0][0]) - ord("R")
    right = ord(pairs[0][1]) - ord("R")
    strokes, current = [], []
    for p in pairs[1:]:
        if p == " R":  # pen up
            if current:
                strokes.append(current)
            current = []
        else:
            current.append([ord(p[0]) - ord("R"), ord(p[1]) - ord("R")])
    if current:
        strokes.append(current)
    return left, right, strokes


def main() -> int:
    try:
        req = urllib.request.Request(URL, headers={"User-Agent": "curve-cut-vendor"})
        with urllib.request.urlopen(req, timeout=60) as r:
            raw = r.read().decode("ascii")
    except Exception as e:  # noqa: BLE001
        print(f"FAIL download {URL}: {e}")
        return 1

    records = unwrap_lines(raw)
    if len(records) < 95:  # need at least printable ASCII 0x20..0x7E
        print(f"FAIL: expected ≥95 glyph records, got {len(records)}")
        return 1

    glyphs = {}
    for i, rec in enumerate(records[:95]):
        ch = chr(0x20 + i)
        try:
            left, right, strokes = parse_glyph(rec)
        except ValueError as e:
            print(f"FAIL parsing glyph {ch!r}: {e}")
            return 1
        glyphs[ch] = {"l": left, "r": right, "s": strokes}

    # Sanity: the glyphs Big Print actually engraves must have ink.
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-":
        if not glyphs[ch]["s"]:
            print(f"FAIL: glyph {ch!r} has no strokes")
            return 1

    js = (
        "// Hershey 'futural' single-stroke font (public domain, A.V. Hershey / US NBS 1967).\n"
        "// Generated by tools/vendor_hershey.py — do not edit by hand.\n"
        "// Format: glyphs[char] = { l, r: left/right extents, s: strokes as [x,y][] }.\n"
        "// Coordinates are Hershey units (~21 = cap height), y grows DOWNWARD.\n"
        "window.HERSHEY_FONT = " + json.dumps({"capHeight": 21, "glyphs": glyphs}, separators=(",", ":")) + ";\n"
    )
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(js, encoding="utf-8")
    print(f"ok   {DEST.relative_to(ROOT)}  ({DEST.stat().st_size:,} bytes, {len(glyphs)} glyphs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
